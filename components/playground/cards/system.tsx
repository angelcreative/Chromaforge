export const CodeSnippetCard: React.FC<{ css?: string }> = ({ css }) => {
  const [copied, setCopied] = useState(false);
  const text = css ?? ':root {\n  --accent: …;\n}';
  const copy = () => { navigator.clipboard?.writeText(text).catch(() => {}); setCopied(true); setTimeout(() => setCopied(false), 1200); };
  return (
    <Card title="Code snippet">
      <div className="row between"><h3>tokens.css</h3><Button variant="plain" icon style={{ height: 30, width: 30 }} aria-label={copied ? 'Copied' : 'Copy'} onClick={copy}>{copied ? <Check {...sm} /> : <Copy {...sm} />}</Button></div>
      <pre className="code mono mt"><span className="c">/* generated by Chromaforge */</span>{'\n'}{text.split('\n').map((line, i) => {
        const m = line.match(/^(\s*)(--[\w-]+):\s*(.+);$/);
        return m ? <React.Fragment key={i}>{m[1]}<span className="k">{m[2]}</span>: <span className="s">{m[3]}</span>;{'\n'}</React.Fragment> : <React.Fragment key={i}>{line}{'\n'}</React.Fragment>;
      })}</pre>
    </Card>
  );
};

